CREATE TABLE IMPORT_LOCK (
    LOCK_KEY         VARCHAR2(128) PRIMARY KEY,
    OWNER_NAME       VARCHAR2(256),
    SERVER_NAME      VARCHAR2(256),
    LOCKED_AT        TIMESTAMP,
    LEASE_UNTIL      TIMESTAMP,
    UPDATED_AT       TIMESTAMP,
    CREATED_AT       TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE IMPORT_BATCH_STATUS (
    ID                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FILE_NAME         VARCHAR2(255) NOT NULL,
    FILE_PATH         VARCHAR2(1000) NOT NULL,
    FILE_SIZE         NUMBER,
    STATUS            VARCHAR2(30) DEFAULT 'READY',
    SERVER_NAME       VARCHAR2(256),
    USER_NAME         VARCHAR2(256),
    LOCK_OWNER        VARCHAR2(256),
    ROWS_READ        NUMBER DEFAULT 0,
    ROWS_INSERTED    NUMBER DEFAULT 0,
    STARTED_AT        TIMESTAMP,
    ENDED_AT          TIMESTAMP,
    ERROR_MESSAGE     CLOB,
    CREATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP,
    UPDATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE IMPORT_STAGING (
    ID                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BATCH_ID          NUMBER NOT NULL,
    SHEET_NAME        VARCHAR2(200),
    ROW_NUMBER        NUMBER,
    RAW_ROW           CLOB,
    CREATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT FK_IMPORT_STAGING_BATCH
        FOREIGN KEY (BATCH_ID) REFERENCES IMPORT_BATCH_STATUS(ID)
);

CREATE INDEX IX_IMPORT_BATCH_STATUS_STATUS ON IMPORT_BATCH_STATUS (STATUS);
CREATE INDEX IX_IMPORT_BATCH_STATUS_UPDATED_AT ON IMPORT_BATCH_STATUS (UPDATED_AT);
CREATE INDEX IX_IMPORT_STAGING_BATCH_ID ON IMPORT_STAGING (BATCH_ID);

INSERT INTO IMPORT_LOCK (LOCK_KEY, OWNER_NAME, SERVER_NAME, LOCKED_AT, LEASE_UNTIL, UPDATED_AT, CREATED_AT)
VALUES ('EXCEL_IMPORT_LOCK', NULL, NULL, SYSTIMESTAMP, SYSTIMESTAMP, SYSTIMESTAMP, SYSTIMESTAMP);

